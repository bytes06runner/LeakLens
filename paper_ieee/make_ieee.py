"""Build the IEEE conference version (IEEEtran) of the paper from paper/leaklens_paper.tex.

    python paper_ieee/make_ieee.py

The body (Introduction to Acknowledgement), the abstract and the keywords are copied verbatim from the article
version, so both versions say exactly the same thing. Only the class, title block and bibliography mechanism
change; the generated tables are copied next to the IEEE source so the folder compiles on its own.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "paper" / "leaklens_paper.tex"
TABLES = ["comparison_table.tex", "yang_measured_table.tex", "baselines_table.tex", "impact_table.tex"]

src = SRC.read_text()
title = re.search(r"\{\\LARGE\\bfseries (.*?)\\par\}", src, re.S)[1].strip()
abstract = re.search(r"\\noindent\\textbf\{Abstract\.\}\n(.*?)\n\n\\vspace", src, re.S)[1].strip()
keywords = re.search(r"\\noindent\\textbf\{Keywords:\} (.*?)\n\\end\{minipage\}", src, re.S)[1].strip()
body = src[src.index("\n\\section{Introduction}\n") + 1:src.index(r"\begin{thebibliography}")].rstrip()
body = body.replace(r"\section*{Acknowledgement}", r"\section*{Acknowledgment}")
body = body.replace("Figure~\\ref", "Fig.~\\ref")  # IEEE style: "Fig. 1" in running text
# The two text-heavy tables (I and II) are set one size smaller, as is usual for large IEEE tables.
body = body.replace("\\label{tab:design}\n\\footnotesize", "\\label{tab:design}\n\\scriptsize")
assert "\\label{tab:design}\n\\scriptsize" in body
body = body.replace("\\label{tab:types}\n\\footnotesize", "\\label{tab:types}\n\\scriptsize")
assert "\\label{tab:types}\n\\scriptsize" in body

# All six authors share one affiliation, so they are set in one IEEE author block (IEEEtran's form for
# authors with a common affiliation) instead of six identical blocks.
names = ["Srijeet Prasad Banerjee", "Adrish Sarkar", "Ankur Roy", "Sayandeep Dey", "Soumyarik Mukherjee",
         "Sayan Hazra"]
author_tex = (r"\IEEEauthorblockN{" + ", ".join(names[:3]) + r",\\ " + ", ".join(names[3:5]) + " and " + names[5]
              + "}\n" + r"\IEEEauthorblockA{\textit{Department of Information Technology}, "
              r"\textit{Guru Nanak Institute of Technology}, Kolkata, India}")

preamble = r"""% LeakLens, IEEE conference version. Generated by paper_ieee/make_ieee.py from paper/leaklens_paper.tex;
% edit the article version and re-run the script rather than editing this file.
\documentclass[conference]{IEEEtran}
\IEEEoverridecommandlockouts
\usepackage[T1]{fontenc}
\usepackage{mathptmx}
\usepackage{cite}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{graphicx}
\usepackage{textcomp}
\usepackage{xcolor}
\usepackage{booktabs}
\usepackage{tabularx}
\usepackage{array}
\usepackage{multirow}
\usepackage{listings}
\usepackage{enumitem}
\usepackage{tikz}
\usetikzlibrary{arrows.meta,positioning}
\usepackage{url}
\def\BibTeX{{\rm B\kern-.05em{\sc i\kern-.025em b}\kern-.08em
    T\kern-.1667em\lower.7ex\hbox{E}\kern-.125emX}}

\setlist{nosep,leftmargin=1.3em}
\setlength{\textfloatsep}{8pt plus 2pt minus 2pt}
\setlength{\floatsep}{6pt plus 2pt minus 2pt}
\setlength{\dbltextfloatsep}{8pt plus 2pt minus 2pt}
\setlength{\dblfloatsep}{6pt plus 2pt minus 2pt}
\definecolor{codebg}{HTML}{F5F6F8}
\definecolor{codegrey}{HTML}{5A626B}
\definecolor{navy}{HTML}{1F4E79}
\lstset{
  basicstyle=\ttfamily\scriptsize,
  backgroundcolor=\color{codebg},
  frame=single, rulecolor=\color{codebg},
  breaklines=true, columns=fullflexible, keepspaces=true,
  showstringspaces=false, xleftmargin=2pt, xrightmargin=2pt,
  aboveskip=5pt, belowskip=3pt,
  commentstyle=\color{codegrey}
}
\newcommand{\tool}{LeakLens}
\newcommand{\code}[1]{\texttt{#1}}
"""

out = (preamble + "\n\\begin{document}\n\n"
       + f"\\title{{{title}}}\n\n\\author{{\n{author_tex}\n}}\n\n\\maketitle\n\n"
       + f"\\begin{{abstract}}\n{abstract}\n\\end{{abstract}}\n\n"
       + f"\\begin{{IEEEkeywords}}\n{keywords}\n\\end{{IEEEkeywords}}\n\n"
       + body + "\n\n\\bibliographystyle{IEEEtran}\n\\bibliography{references}\n\n\\end{document}\n")
(HERE / "leaklens_ieee.tex").write_text(out)
for t in TABLES:
    shutil.copy(SRC.parent / t, HERE / t)
print("wrote", HERE / "leaklens_ieee.tex")
