"""File-level comparison of the Yang et al. analyser and LeakLens on the same injected files.

    python baselines/yang/score_file_level.py YANG_RESULTS_JSON LEAKLENS_RUN_DIR OUT_DIR

The Yang analyser lists, per leak type, the lines of the *evaluation* call it considers affected, not the line
that causes the leak, so the line-overlap rule of EVAL_PROTOCOL.md section 2 cannot be applied to it. Here both
tools are scored per file and type: a tool is right about type T in a file when it reports T and the file has a
labelled leak of type T (or one that accepts T as an alternative type). This rule is looser than the protocol's
and is used for this comparison only (EVAL_CHANGES.md #6). A hit counts for the label's primary type, so the Yang
analyser gets credit under `temporal` when it reports whole-series scaling as preprocessing leakage.

The Yang analyser takes Python files only (its README: notebooks must be converted first), so notebooks are given
to it as the benchmark's plain-script rendering. A file it cannot analyse counts as analysed with no finding
(CLAUDE.md Rule 5).
"""

from __future__ import annotations

import csv
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
YANG_TYPES = {
    "Pre-processing leakage": "preprocessing",
    "Overlap leakage": "overlap",
    "No independence test data": "multi_test",
}
TYPES = ["preprocessing", "overlap", "multi_test", "group", "temporal", "target_derived"]


def prf(tp: int, fp: int, fn: int) -> tuple[str, str]:
    return (f"{tp / (tp + fp):.2f}" if tp + fp else "n/a", f"{tp / (tp + fn):.2f}" if tp + fn else "n/a")


def main() -> None:
    yang = json.loads(Path(sys.argv[1]).read_text())
    run, out = Path(sys.argv[2]), Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    items = sorted(yang["items"])
    # per file: primary type of each labelled leak -> the types that label accepts
    truth: dict[str, dict[str, set[str]]] = defaultdict(dict)
    for r in csv.DictReader((ROOT / "benchmark/injected/_groundtruth/labels.csv").open()):
        if r["item_id"] in yang["items"]:
            acc = {r["type"], *[a for a in r["alt_types"].split(";") if a and a != "nan"]}
            truth[r["item_id"]].setdefault(r["type"], set()).update(acc)
    ll: dict[str, set[str]] = defaultdict(set)
    for line in (run / "findings.jsonl").open():
        rec = json.loads(line)
        if rec["seed"] == 0 and rec["item_id"] in yang["items"]:
            ll[rec["item_id"]] = {f["type"] for f in rec["static"] if f["confidence"] != "low"}

    def reported(item: str, converted: bool) -> set[str] | None:
        v = yang["items"][item]
        s = v["summary"]
        if s is None and converted:
            s = (v.get("as_script") or {}).get("summary")
        if s is None:
            return None
        return {YANG_TYPES[k] for k, x in s.items() if k in YANG_TYPES and x["detected"] > 0}

    # The tool's README says notebooks must be converted to Python files first, so the converted run is the tool
    # used as documented. Passing an .ipynb file directly gives no report; that is noted, not scored against it.
    tools = {
        "Yang et al. (notebooks converted to .py first, as its README requires)": lambda it: reported(it, True),
        "LeakLens, static": lambda it: ll[it],
    }
    direct = sum(1 for it in items if reported(it, False) is None)
    rows, md = (
        [],
        [
            "# Yang et al. (ASE 2022) and LeakLens on the same files, scored per file and type",
            "",
            f"Split: **{yang['split']}** of the injected benchmark, {len(items)} files. Yang analyser at commit "
            f"`{yang['yang_commit'][:8]}`, default command, Souffle route: {yang.get('souffle_route')}. LeakLens: "
            f"static mode, findings of confidence medium or higher, run `{run.name}`.",
            "",
            "A tool is right about a type in a file when it reports that type and the file has a labelled leak that "
            "accepts it; the hit counts for that label's primary type. This is looser than the protocol's "
            "line-overlap rule and is used here only because the Yang analyser reports the evaluation line, not the "
            "leaking line (EVAL_CHANGES.md #6).",
            "",
        ],
    )
    if yang["split"] == "TEST":
        md += [
            "**TEST: neither tool was tuned on these files. They are still files generated by this project's own "
            "mutation operators, of the same kinds LeakLens was developed against, so the comparison favours "
            "LeakLens; the human-labelled real notebooks are the fair test and are not done.**",
            "",
        ]
    if yang["split"] == "DEV":
        md += [
            "**DEV: LeakLens's rules were written on these files; the Yang analyser has never seen them. This "
            "table is not a fair accuracy comparison. It shows which types each tool covers and that the baseline "
            "runs.**",
            "",
        ]
    for name, fn in tools.items():
        analysed = sum(1 for it in items if fn(it) is not None)
        clean = [it for it in items if not truth[it]]
        alarms = sum(1 for it in clean if fn(it))
        md += [
            f"## {name}",
            "",
            f"Files analysed: {analysed} of {len(items)}. Leak-free files with a finding: {alarms} of {len(clean)}.",
            "",
            "| type | files with this leak | TP | FP | FN | precision | recall |",
            "|---|---|---|---|---|---|---|",
        ]
        tp, fp, fn_ = defaultdict(int), defaultdict(int), defaultdict(int)
        for it in items:
            got = fn(it) or set()
            for primary, accepted in truth[it].items():  # a hit counts for the label's primary type (protocol s.2)
                if got & accepted:
                    tp[primary] += 1
                else:
                    fn_[primary] += 1
            for t in got:
                if not any(t in accepted for accepted in truth[it].values()):
                    fp[t] += 1
        for t in TYPES:
            claimed = not (name.startswith("Yang") and t not in YANG_TYPES.values())
            n = tp[t] + fn_[t]
            p, r = prf(tp[t], fp[t], fn_[t])
            note = "" if claimed else " (not a type it claims)"
            md.append(f"| {t}{note} | {n} | {tp[t]} | {fp[t]} | {fn_[t]} | {p if claimed else 'n/a'} | {r} |")
            rows.append(
                {"tool": name, "type": t, "files": n, "tp": tp[t], "fp": fp[t], "fn": fn_[t], "claimed": claimed}
            )
        md.append("")
    md += [
        f"Given the {direct} notebook files directly (.ipynb), the Yang analyser exits without a report; its README "
        "says notebooks must be converted first. The conversion used here is this benchmark's own plain-script "
        "rendering of each notebook (`_groundtruth/leaky_py`).",
        "",
    ]
    runs = [v.get("as_script") or v for v in yang["items"].values()]
    secs = [v["seconds"] for v in runs if v.get("seconds")]
    md.append(
        f"Yang analyser time per file: median {statistics.median(secs):.1f} s, mean {statistics.mean(secs):.1f} s "
        "(Kaggle CPU). LeakLens static time is in the run's REPORT.md (laptop); the machines differ."
    )
    (out / "YANG_VS_LEAKLENS.md").write_text("\n".join(md) + "\n")
    with (out / "file_level.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
